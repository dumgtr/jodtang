export interface BenchmarkCase {
  id: string;
  tier: 'A_SIMPLE' | 'B_COLLOQUIAL' | 'C_NATURAL' | 'D_DATE' | 'E_AMBIGUOUS' | 'F_COMPLEX';
  input: string;
  reference_date: string;
  expected: Array<{
    type: 'EXPENSE' | 'INCOME' | 'TRANSFER';
    amount: number;
    category: string;
    merchant: string;
    description: string;
    date: string;
  }>;
}

const refDate = '2026-08-21';
const dataset: BenchmarkCase[] = [];

function addCase(
  tier: BenchmarkCase['tier'],
  input: string,
  expected: BenchmarkCase['expected'],
  customRefDate: string = refDate
) {
  const tierPrefix = tier.charAt(0);
  const countInTier = dataset.filter((c) => c.tier === tier).length + 1;
  const id = `TC_${tierPrefix}_${String(countInTier).padStart(3, '0')}`;
  dataset.push({
    id,
    tier,
    input,
    reference_date: customRefDate,
    expected,
  });
}

